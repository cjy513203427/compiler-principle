/** Visible text, accessible names and the title that still contain Chinese (the 中文 link aside). */
async function chineseLeftovers(page: Page) {
  return page.evaluate(() => {
    const CJK = /[　-〿一-鿿＀-￯]/;
    const exempt = (el: Element | null) => !el || !!el.closest('[lang="zh-CN"], script, style');
    const found: string[] = [];
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const text = node.textContent ?? '';
      if (CJK.test(text) && !exempt(node.parentElement)) found.push(text.trim().slice(0, 80));
    }
    // Text generated by CSS (::before / ::after content) is not in the DOM but still shows.
    for (const el of document.body.querySelectorAll('*')) {
      if (exempt(el)) continue;
      for (const pseudo of ['::before', '::after']) {
        const content = getComputedStyle(el, pseudo).content;
        if (content && content !== 'none' && CJK.test(content)) found.push(`${pseudo} ${content}`);
      }
    }
    for (const el of document.querySelectorAll('[aria-label], [title], [alt], [placeholder]')) {
      if (exempt(el)) continue;
      for (const name of ['aria-label', 'title', 'alt', 'placeholder']) {
        const value = el.getAttribute(name);
        if (value && CJK.test(value)) found.push(`${name}=${value.slice(0, 80)}`);
      }
    }
    // Editable inputs hold program text, whose comments are translated too.
    for (const field of document.querySelectorAll<HTMLTextAreaElement | HTMLInputElement>('textarea, input')) {
      if (CJK.test(field.value)) found.push(`value=${field.value.slice(0, 80)}`);
    }
    if (CJK.test(document.title)) found.push(`document.title=${document.title}`);
    return found;
  });
}

const overflow = (page: Page) =>
  page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);

/**
 * Text that spills out of its box: SVG text wider than the rect drawn in the same group or
 * leaving the drawing, and HTML text wider than an element that is not meant to scroll.
 * Translations are longer than the Chinese source, so fixed boxes are the usual victims.
 */
async function spilledText(page: Page) {
  return page.evaluate(() => {
    const found: string[] = [];
    const name = (el: Element) => (el.textContent ?? '').trim().slice(0, 60);
    const scrolls = (el: Element | null) => {
      for (let e = el; e; e = e.parentElement)
        if (['auto', 'scroll'].includes(getComputedStyle(e).overflowX)) return true;
      return false;
    };
    for (const text of document.querySelectorAll<SVGTextElement>('svg text')) {
      if (!text.getClientRects().length || !name(text)) continue;
      const t = text.getBoundingClientRect();
      for (const rect of [...(text.parentElement?.children ?? [])].filter((el) => el.tagName === 'rect')) {
        const r = rect.getBoundingClientRect();
        const cx = (t.left + t.right) / 2;
        const cy = (t.top + t.bottom) / 2;
        const inside = cx > r.left && cx < r.right && cy > r.top && cy < r.bottom;
        if (inside && (t.left < r.left - 1 || t.right > r.right + 1))
          found.push(`“${name(text)}” is wider than its box`);
      }
      const s = text.ownerSVGElement!.getBoundingClientRect();
      // A drawing inside a scroll container may be wider than the screen on purpose.
      if ((t.left < s.left - 1 || t.right > s.right + 1) && !scrolls(text.ownerSVGElement))
        found.push(`“${name(text)}” leaves the drawing`);
    }
    for (const el of document.querySelectorAll('body *')) {
      if (el.closest('svg, pre, code, textarea, select') || !el.getClientRects().length) continue;
      if (['auto', 'scroll', 'hidden', 'clip'].includes(getComputedStyle(el).overflowX)) continue;
      const ownText = [...el.childNodes].some((n) => n.nodeType === 3 && n.textContent?.trim());
      if (ownText && el.clientWidth > 0 && el.scrollWidth > el.clientWidth + 1)
        found.push(`“${name(el)}” is wider than its <${el.tagName.toLowerCase()}>`);
    }
    return found;
  });
}

/**
 * Text drawn on top of other text: an SVG label running into another label or into a small
 * legend swatch / marker, or HTML text lines colliding (e.g. with a button placed beside them).
 * Translations are longer than the Chinese source, so labels laid out at fixed offsets collide.
 * Boxes are trimmed to the glyphs and to what clipping ancestors leave visible.
 */
async function overlappingText(page: Page) {
  // Let finite transitions settle so an animation frame is not mistaken for the layout.
  await page.evaluate(async () => {
    await new Promise((done) => requestAnimationFrame(() => requestAnimationFrame(done)));
    const finite = document
      .getAnimations()
      .filter((a) => a.effect?.getComputedTiming().endTime !== Infinity);
    await Promise.race([
      Promise.all(finite.map((a) => a.finished.catch(() => undefined))),
      new Promise((done) => setTimeout(done, 1500)),
    ]);
  });
  return page.evaluate(() => {
    type Box = { x0: number; x1: number; y0: number; y1: number };
    const found = new Set<string>();
    const name = (el: Element) => (el.textContent ?? '').trim().replace(/\s+/g, ' ').slice(0, 50);
    const shown = (el: Element) =>
      el.getClientRects().length > 0 &&
      el.checkVisibility({
        opacityProperty: true,
        visibilityProperty: true,
        contentVisibilityAuto: true,
      });
    const hit = (a: Box, b: Box, pad: number) =>
      Math.min(a.x1, b.x1) - Math.max(a.x0, b.x0) > pad &&
      Math.min(a.y1, b.y1) - Math.max(a.y0, b.y0) > pad;
    // Starts at the parent of el; pass a text node to include its own element (e.g. .sr-only).
    const visiblePart = (box: Box, el: Node): Box | null => {
      for (let e = el.parentElement; e && e !== document.documentElement; e = e.parentElement) {
        const style = getComputedStyle(e);
        if (style.overflowX === 'visible' && style.overflowY === 'visible') continue;
        const r = e.getBoundingClientRect();
        box = {
          x0: Math.max(box.x0, r.left),
          x1: Math.min(box.x1, r.right),
          y0: Math.max(box.y0, r.top),
          y1: Math.min(box.y1, r.bottom),
        };
      }
      return box.x1 - box.x0 > 1 && box.y1 - box.y0 > 1 ? box : null;
    };
    /** Union of the character cells, trimmed to roughly the cap height. */
    const glyphs = (text: SVGTextElement): Box | null => {
      const m = text.getScreenCTM();
      const b = { x0: Infinity, x1: -Infinity, y0: Infinity, y1: -Infinity };
      for (let i = 0; m && i < text.getNumberOfChars(); i++) {
        // Chrome returns an SVGRect here (typed as DOMRect): it has no right / bottom.
        let x0: number, y0: number, x1: number, y1: number;
        try {
          const cell = text.getExtentOfChar(i);
          [x0, y0, x1, y1] = [cell.x, cell.y, cell.x + cell.width, cell.y + cell.height];
        } catch {
          continue;
        }
        for (const [x, y] of [
          [x0, y0],
          [x1, y1],
          [x0, y1],
          [x1, y0],
        ]) {
          const p = new DOMPoint(x, y).matrixTransform(m);
          b.x0 = Math.min(b.x0, p.x);
          b.x1 = Math.max(b.x1, p.x);
          b.y0 = Math.min(b.y0, p.y);
          b.y1 = Math.max(b.y1, p.y);
        }
      }
      if (!(b.x1 > b.x0)) return null;
      const h = b.y1 - b.y0;
      return visiblePart(
        { x0: b.x0 + 0.5, x1: b.x1 - 0.5, y0: b.y0 + h * 0.22, y1: b.y1 - h * 0.18 },
        text,
      );
    };
    const main = document.querySelector('main') ?? document.body;
    for (const svg of main.querySelectorAll('svg')) {
      if (!shown(svg)) continue;
      const texts = [...svg.querySelectorAll('text')]
        .filter((t) => name(t) && !t.closest('defs') && shown(t))
        .map((t) => ({ t, b: glyphs(t) }))
        .filter((x): x is { t: SVGTextElement; b: Box } => !!x.b);
      for (let i = 0; i < texts.length; i++)
        for (let j = i + 1; j < texts.length; j++)
          if (hit(texts[i].b, texts[j].b, 0.5))
            found.add(`“${name(texts[i].t)}” overlaps “${name(texts[j].t)}”`);
      for (const shape of svg.querySelectorAll('rect, circle, path, polygon')) {
        const r = shape.getBoundingClientRect();
        if (r.width > 16 || r.height > 16 || r.width * r.height < 4) continue;
        if (shape.closest('defs, marker, clipPath, mask') || !shown(shape)) continue;
        const style = getComputedStyle(shape);
        if (style.fill === 'none' && style.stroke === 'none') continue;
        const s = { x0: r.left, x1: r.right, y0: r.top, y1: r.bottom };
        for (const { t, b } of texts) {
          const cx = (b.x0 + b.x1) / 2,
            cy = (b.y0 + b.y1) / 2;
          if (cx > s.x0 && cx < s.x1 && cy > s.y0 && cy < s.y1) continue; // drawn on its marker
          if (hit(b, s, 1.5)) found.add(`“${name(t)}” runs into a swatch or marker`);
        }
      }
    }
    const lines: { node: Text; el: Element; b: Box }[] = [];
    const walker = document.createTreeWalker(main, NodeFilter.SHOW_TEXT);
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const el = node.parentElement;
      if (!el || !node.textContent?.trim()) continue;
      if (el.closest('svg, select, textarea') || !shown(el)) continue;
      const range = document.createRange();
      range.selectNodeContents(node);
      for (const r of range.getClientRects()) {
        const h = r.height;
        const b = visiblePart(
          { x0: r.left + 0.5, x1: r.right - 0.5, y0: r.top + h * 0.25, y1: r.bottom - h * 0.25 },
          node,
        );
        if (b) lines.push({ node: node as Text, el, b });
      }
    }
    lines.sort((a, b) => a.b.y0 - b.b.y0);
    for (let i = 0; i < lines.length; i++)
      for (let j = i + 1; j < lines.length && lines[j].b.y0 < lines[i].b.y1; j++)
        if (lines[i].node !== lines[j].node && hit(lines[i].b, lines[j].b, 1))
          found.add(`“${name(lines[i].el)}” overlaps “${name(lines[j].el)}”`);
    return [...found];
  });
}

/** Opens the course contents on narrow screens, where the language switch lives. */
async function openContents(page: Page, label: string) {
  const toggle = page.getByRole('button', { name: label });
  if ((await toggle.isVisible()) && (await toggle.getAttribute('aria-expanded')) !== 'true')
    await toggle.click();
}

async function check(page: Page, label: string) {
  expect(await chineseLeftovers(page), label).toEqual([]);
  expect(await overflow(page), `${label} horizontal overflow`).toBeLessThanOrEqual(1);
  expect(await spilledText(page), `${label} text outside its box`).toEqual([]);
  expect(await overlappingText(page), `${label} overlapping text`).toEqual([]);
}

function watch(page: Page) {
  const problems: string[] = [];
  page.on('pageerror', (error) => problems.push(`pageerror: ${error.message}`));
  page.on('console', (message) => {
    if (message.text().includes('[i18n] missing')) problems.push(message.text());
  });
  return problems;
}

for (const locale of ['en', 'de'] as const)
  test.describe(`${locale} pages`, () => {
    const names = NAMES[locale];
    for (const lab of LABS)
      test(`${lab}: first step, final result and notes are translated and fit the screen`, async ({ page }) => {
        const problems = watch(page);
        await page.goto(`/${locale}/?lab=${lab}`);
        await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
        await expect(page.locator('html')).toHaveAttribute('lang', locale);
        await check(page, `${lab} first step`);
        const final = page.getByRole('button', { name: names.final });
        if (await final.isVisible()) {
          await final.click();
          await check(page, `${lab} final step`);
        }
        for (const tab of names.tabs) {
          await page.locator('.lesson-tabs').getByRole('button', { name: tab, exact: true }).click();
          await check(page, `${lab} · ${tab}`);
        }
        expect(problems).toEqual([]);
      });

    for (const route of ['', '?lab=notes', '?lab=sources'])
      test(`${route || 'home'} is translated and fits the screen`, async ({ page }) => {
        const problems = watch(page);
        await page.goto(`/${locale}/${route}`);
        await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
        await check(page, route || 'home');
        // Links inside the site stay in the page language.
        for (const href of await page
          .locator('main a[href^="/"]')
          .evaluateAll((links) => links.map((link) => link.getAttribute('href'))))
          expect(href, 'internal links keep the language').toMatch(new RegExp(`^/${locale}/`));
        expect(problems).toEqual([]);
      });

    test('assembly appendix tabs are translated and fit the screen', async ({ page }) => {
      const problems = watch(page);
      await page.goto(`/${locale}/?lab=assembly`);
      await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
      await check(page, 'assembly');
      for (const tab of names.assemblyTabs) {
        await page.getByRole('button', { name: tab, exact: true }).first().click();
        await check(page, `assembly · ${tab}`);
      }
      expect(problems).toEqual([]);
    });
  });

test('the language switch keeps the lab, its source and step', async ({ page }) => {
  await page.goto('/en/?lab=lr');
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  await page.getByRole('button', { name: NAMES.en.final }).click();
  const step = await page.getByRole('slider', { name: 'Current step' }).inputValue();
  await openContents(page, NAMES.en.contents);
  await page.getByRole('navigation', { name: NAMES.en.languages }).getByRole('link', { name: 'Deutsch' }).click();
  await expect(page).toHaveURL(/\/de\/\?lab=lr/);
  await expect(page.locator('html')).toHaveAttribute('lang', 'de');
  await expect(page.getByRole('slider', { name: 'Aktueller Schritt' })).toHaveValue(step);
  await openContents(page, NAMES.de.contents);
  await page.getByRole('navigation', { name: NAMES.de.languages }).getByRole('link', { name: '中文' }).click();
  await expect(page).toHaveURL(/\/\?lab=lr/);
  expect(new URL(page.url()).pathname).toBe('/');
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
  await expect(page.getByRole('slider', { name: '当前步骤' })).toHaveValue(step);
});
